  var CART_STORAGE_KEY = 'sg_cart_v1';
  function loadStoredCart() {
    try {
      var raw = localStorage.getItem(CART_STORAGE_KEY);
      if (!raw) return {};
      var parsed = JSON.parse(raw);
      return (parsed && typeof parsed === 'object') ? parsed : {};
    } catch (e) { return {}; }
  }
