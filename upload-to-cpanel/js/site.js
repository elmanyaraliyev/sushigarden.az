  (function initCarousel() {
    var track = document.getElementById('carousel-track');
    var prevBtn = document.getElementById('carousel-prev');
    var nextBtn = document.getElementById('carousel-next');
    var dotsWrap = document.getElementById('carousel-dots');
    if (!track) return;

    var slides = track.querySelectorAll('.carousel-slide');
    var dots = dotsWrap ? dotsWrap.querySelectorAll('button') : [];
    var index = 0;
    var autoTimer = null;

    function goTo(i) {
      index = (i + slides.length) % slides.length;
      track.style.transform = 'translateX(-' + (index * 100) + '%)';
      dots.forEach(function (d, di) { d.classList.toggle('active', di === index); });
    }
    function next() { goTo(index + 1); }
    function prev() { goTo(index - 1); }
    function startAuto() {
      stopAuto();
      if (slides.length > 1) autoTimer = setInterval(next, 3000);
    }
    function stopAuto() {
      if (autoTimer) clearInterval(autoTimer);
    }

    if (nextBtn) nextBtn.addEventListener('click', function () { next(); startAuto(); });
    if (prevBtn) prevBtn.addEventListener('click', function () { prev(); startAuto(); });
    dots.forEach(function (d, di) {
      d.addEventListener('click', function () { goTo(di); startAuto(); });
    });

    // barmaqla sürüşdürmə (touch swipe)
    var touchStartX = null;
    track.addEventListener('touchstart', function (e) { touchStartX = e.touches[0].clientX; stopAuto(); }, { passive: true });
    track.addEventListener('touchend', function (e) {
      if (touchStartX === null) return;
      var dx = e.changedTouches[0].clientX - touchStartX;
      if (Math.abs(dx) > 40) { dx < 0 ? next() : prev(); }
      touchStartX = null;
      startAuto();
    });

    goTo(0);
    startAuto();
  })();

