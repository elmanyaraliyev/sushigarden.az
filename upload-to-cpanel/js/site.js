  (function initLang() {
    var switchEl = document.getElementById('lang-switch');
    var trigger = document.getElementById('lang-trigger');
    var menu = document.getElementById('lang-menu');
    var currentFlag = document.getElementById('lang-current-flag');
    var currentCode = document.getElementById('lang-current-code');
    if (!switchEl || !trigger || !menu) return;

    // məhsul/kateqoriya adları üçün ilkin (AZ) mətni saxla ki, geri qayıda bilək
    document.querySelectorAll('[data-i18n-ru], [data-i18n-en]').forEach(function (el) {
      el.setAttribute('data-i18n-az', el.textContent);
    });

    function closeMenu() {
      switchEl.classList.remove('open');
      trigger.setAttribute('aria-expanded', 'false');
    }
    function toggleMenu() {
      var willOpen = !switchEl.classList.contains('open');
      switchEl.classList.toggle('open', willOpen);
      trigger.setAttribute('aria-expanded', willOpen ? 'true' : 'false');
    }

    function applyLang(lang) {
      var dict = SG_STRINGS[lang] || SG_STRINGS.az;
      document.querySelectorAll('[data-i18n]').forEach(function (el) {
        var key = el.getAttribute('data-i18n');
        if (dict[key] !== undefined) el.innerHTML = dict[key];
      });
      document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
        var key = el.getAttribute('data-i18n-placeholder');
        if (dict[key] !== undefined) el.setAttribute('placeholder', dict[key]);
      });
      document.querySelectorAll('[data-i18n-ru], [data-i18n-en]').forEach(function (el) {
        var az = el.getAttribute('data-i18n-az') || '';
        if (lang === 'ru') el.textContent = el.getAttribute('data-i18n-ru') || az;
        else if (lang === 'en') el.textContent = el.getAttribute('data-i18n-en') || az;
        else el.textContent = az;
      });

      var options = menu.querySelectorAll('.lang-option');
      options.forEach(function (b) {
        var isActive = b.getAttribute('data-lang') === lang;
        b.classList.toggle('active', isActive);
        if (isActive && currentFlag && currentCode) {
          currentFlag.innerHTML = b.querySelector('.flag').outerHTML;
          currentCode.textContent = b.getAttribute('data-lang').toUpperCase();
        }
      });

      document.documentElement.setAttribute('lang', lang);
      try { localStorage.setItem('sg_lang', lang); } catch (e) {}
      window.__sgLang = lang;
      if (typeof window.__sgRenderCart === 'function') window.__sgRenderCart();
    }

    trigger.addEventListener('click', function (e) { e.stopPropagation(); toggleMenu(); });
    menu.querySelectorAll('.lang-option').forEach(function (b) {
      b.addEventListener('click', function () { applyLang(b.getAttribute('data-lang')); closeMenu(); });
    });
    document.addEventListener('click', function (e) {
      if (!switchEl.contains(e.target)) closeMenu();
    });
    document.addEventListener('keydown', function (e) {
      if (e.key === 'Escape') closeMenu();
    });

    var saved = 'az';
    try { saved = localStorage.getItem('sg_lang') || 'az'; } catch (e) {}
    applyLang(saved);
  })();

