  function resetCheckoutFields() {
    if (custName) custName.value = '';
    if (custPhone) custPhone.value = '';
    if (custAddress) custAddress.value = '';
    if (custTime) custTime.value = 'asap';
    if (custParty) custParty.value = '';
    if (custNotes) custNotes.value = '';
    currentTip = 0;
    if (tipCustomInput) { tipCustomInput.value = ''; tipCustomInput.style.display = 'none'; }
    if (tipOptions) {
      tipOptions.querySelectorAll('.tip-btn').forEach(function (b) { b.classList.remove('active'); });
      var zeroBtn = tipOptions.querySelector('[data-tip="0"]');
      if (zeroBtn) zeroBtn.classList.add('active');
    }
    if (orderError) orderError.style.display = 'none';
  }

